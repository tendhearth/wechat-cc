const shots = process.env.WECHAT_CC_SECONDARY_SHOTS
async function shot(page: Page, name: string) {
  if (!shots) return
  mkdirSync(shots, { recursive: true })
  await page.screenshot({ path: join(shots, `${name}.png`), animations: 'disabled' })
}
async function boot(page: Page, shimUrl: string) {
  await page.goto(shimUrl)
  await page.waitForFunction(() => document.documentElement.dataset.mode === 'dashboard')
}
async function backstage(page: Page, pane: 'plugins' | 'logs') {
  await clickNav(page, 'sessions')
  await page.locator(`article[data-pane="sessions"] [data-backstage-pane="${pane}"]`).click()
}
