for (const mode of ['empty', 'error'] as const) test(`secondary ${mode} states remain truthful and recoverable`, async ({ page, shimUrl, shim }) => {
  await page.setViewportSize({ width: 760, height: 720 })
  await shim.invoke('demo.seed', { chat_id: owner })
  await secondaryFixtures(page, mode)
  await page.route('**/__invoke', async route => {
    const call = route.request().postDataJSON()
    if (call.command === 'wechat_cli_json_via_file' && call.args?.args?.[0] === 'logs') return route.fulfill({ json: { result: mode === 'empty' ? { ok: true, entries: [], totalLines: 0, logFile: 'channel.log' } : { ok: false, error: 'temporary_unavailable', entries: [], totalLines: 0, logFile: 'channel.log' } } })
    return route.continue()
  })
  await boot(page, shimUrl)
  await clickNav(page, 'recollections')
  await expect(page.locator('#postcard-album')).toContainText(mode === 'empty' ? '还没有' : /失败|没能|无法/)
  await shot(page, `recollections-${mode}`)
  await page.locator('[data-life-category="thoughts"]').click()
  await expect(page.locator('#cc-memory-records')).toContainText(mode === 'empty' ? '还没有' : '没能读取')
  await shot(page, `thoughts-${mode}`)
  await clickNav(page, 'atelier')
  await expect(page.locator('#atelier-gallery')).toContainText(mode === 'empty' ? /还没有|第一幅/ : /无法|失败/)
  await shot(page, `atelier-${mode}`)
  await clickNav(page, 'memory')
  await expect(page.locator('#memory-profile-content')).toContainText(mode === 'empty' ? '还没有可用的会话' : '暂时无法读取记忆')
  if (mode === 'error') {
    await page.locator('#memory-facts-search').fill('查询不会把失败改为空记录')
    await expect(page.locator('#memory-facts-records')).toContainText('暂时无法读取')
  }
  await shot(page, `memory-${mode}`)
  await clickNav(page, 'todos')
  await expect(page.locator('#todos-root')).toContainText(mode === 'empty' ? /没有|还没/ : /无法|失败|没能|读不到/)
  await shot(page, `todos-${mode}`)
  await clickNav(page, 'a2a-agents')
  await expect(page.locator('#fd-catch')).toContainText(mode === 'empty' ? /没有|还没/ : /没能|失败|无法/)
  await shot(page, `forage-${mode}`)
  await page.locator('#fd-tools-summary').click()
  await expect(page.locator('#fd-mailbox')).toContainText(mode === 'empty' ? /还没|没有/ : /无法|失败|没能|读不到/)
  await page.locator('#fd-mailbox').scrollIntoViewIfNeeded()
  await shot(page, `mail-${mode}`)
  await backstage(page, 'plugins')
  await expect(page.locator('#plugins-list')).toContainText(mode === 'empty' ? '还没有插件' : '加载失败')
  await shot(page, `plugins-${mode}`)
  // A retry must recover the actual list rather than leave a stale loading label.
  if (mode === 'error') {
    await secondaryFixtures(page, 'normal')
    await page.locator('#plugins-refresh-btn').click()
    await expect(page.locator('#plugins-list')).toContainText('花园笔记')
  }
  await backstage(page, 'logs')
  await expect(page.locator('#logs-body')).toContainText(mode === 'empty' ? '没有日志' : '读取失败')
  await shot(page, `logs-${mode}`)
})

