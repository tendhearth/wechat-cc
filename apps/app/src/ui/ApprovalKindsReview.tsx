import { useMemo, useRef } from 'react'
import { ScrollView, View } from 'react-native'
import { SafeAreaView } from 'react-native-safe-area-context'
import { CliSessionRow, MatterDetail, toolPermissionDisplay, type PermissionDisplay } from '@wechat-cc/protocol'
import { makeDemoBackend } from '../backend/demo'
import { demoName } from '../backend/demo-data'
import { useLang } from '../i18n/useLang'
import { DETAIL } from '../backend/fixtures'
import { approvalView } from '../view/approval'
import { TERMINAL_PERMISSION_SUMMARY_LIMIT } from '../view/terminal'
import { OfflineReviewProvider } from '../state/BackendProvider'
import { PermissionCard } from './PermissionCard'
import { TerminalPermission } from './TerminalPermission'
import { space } from './tokens'
import { useTheme } from './useTheme'

const projectPath = '/sample/windmill'
const edits = [
  { old_string: 'label = "Draft"', new_string: 'label = "Ready"' },
  { old_string: 'cards = 2\ncolumns = 1', new_string: 'cards = 4\ncolumns = 2' },
]
const patch: PermissionDisplay = { body: { kind: 'patch', files: [
  { path: projectPath + '/src/cards.ts', change: 'update', movePath: projectPath + '/src/gallery-cards.ts',
    diff: '@@ -1 +1 @@\n-export const cards = 2\n+export const cards = 4' },
  { path: projectPath + '/src/labels.ts', change: 'add', diff: '+export const label = "Ready"' },
] } }
const patchRaw = patch.body.kind === 'patch' ? patch.body.files.map(file => [file.path, file.change, ...(file.movePath ? [file.movePath] : []), file.diff].join('\n')).join('\n\n') : ''
const codexScope = '\nExecution environment: local'
const commandAtLimit = 'printf %s ' + 'x'.repeat(TERMINAL_PERMISSION_SUMMARY_LIMIT - 'printf %s '.length)
const terminalEdit = { file_path: projectPath + '/src/gallery.ts', old_string: 'export const status = "draft"', new_string: 'export const status = "ready"' }
const command = 'npm test\nnpm run preview'
const reason = 'Check the gallery before opening its preview.'
const acpEdit: PermissionDisplay = { body: { kind: 'edit', path: projectPath + '/src/labels.ts', changes: [
  { before: 'export const label = "Draft"\n', after: 'export const label = "Ready"\n' },
] } }
const samples: Array<{ id: string; tool: string; raw: string; display?: PermissionDisplay; cwd?: string }> = [
  { id: 'command', tool: 'Bash', raw: 'command=' + [
    'printf "%s\\n" "Preparing the sample gallery with a longer label that wraps on a phone"',
    'printf "%s\\n" north', 'printf "%s\\n" south', 'printf "%s\\n" east', 'printf "%s\\n" west',
    'printf "%s\\n" spring', 'printf "%s\\n" summer', 'printf "%s\\n" autumn', 'printf "%s\\n" winter',
  ].join('\n') },
  { id: 'edit', tool: 'MultiEdit', raw: 'input=' + JSON.stringify({ file_path: projectPath + '/src/gallery.ts', edits }) },
  { id: 'write', tool: 'Write', raw: 'input=' + JSON.stringify({ file_path: projectPath + '/notes.txt', content: 'Gallery checklist\nSort the cards\nReview the labels\n' }) },
  { id: 'patch', tool: 'fileChange', raw: patchRaw, display: patch },
  { id: 'fields', tool: 'mcp__gallery__list', raw: 'mcp__gallery__list\n{"collection":"Windmill","limit":4,"filters":{"season":"spring"}}' },
  { id: 'url', tool: 'WebFetch', raw: 'input={"url":"https://gallery.example/collections/windmill","prompt":"List the collection names."}' },
  { id: 'query', tool: 'WebSearch', raw: 'input={"query":"paper windmill exhibition"}' },
  { id: 'text', tool: 'GalleryTool', raw: 'Preview generated by the gallery tool.\nDetails will be available after the review.' },
  { id: 'codex-command', tool: 'commandExecution', raw: `${command}\nWorking directory: ${projectPath}/src\n${reason}${codexScope}`,
    cwd: projectPath + '/src', display: { note: reason, body: { kind: 'command', command },
      extra: [{ name: 'Scope', value: codexScope.trim() }] } },
  { id: 'codex-file', tool: 'fileChange', raw: patchRaw + codexScope, display: patch },
  { id: 'acp-diff', tool: 'edit', raw: 'Edit label\n' + projectPath + '/src/labels.ts\nBefore:\nexport const label = "Draft"\n\nAfter:\nexport const label = "Ready"\n', display: acpEdit },
]

export function ApprovalKindsReview() {
  const lang = useLang()
  const { c } = useTheme()
  const backend = useMemo(() => makeDemoBackend({ lang }), [lang])
  const scroll = useRef<ScrollView>(null)
  return <OfflineReviewProvider backend={backend} lang={lang}>
    <SafeAreaView style={{ flex: 1, backgroundColor: c.paper }}>
      <ScrollView ref={scroll} testID="approval-kinds" contentContainerStyle={{ paddingHorizontal: space.xl, paddingBottom: space.xl, gap: space.xxl }}>
        {samples.map(({ id, tool, raw, display, cwd }) => {
          const executor = id === 'patch' || id.startsWith('codex-') ? 'codex' : id === 'acp-diff' ? 'cursor' : 'claude'
          const matterTitle = lang === 'zh-Hans' ? '纸风车展览' : 'Paper windmill exhibition'
          const wire = MatterDetail.parse({
            ...DETAIL, matter: { ...DETAIL.matter, title: matterTitle, projectPath },
            task: { ...DETAIL.task, providerId: executor, path: projectPath },
            permissions: [{ ...DETAIL.permissions[0], id, tool, description: raw, display, cwd }],
          })
          const v = approvalView(wire, {})
          return v.kind === 'card' ? <View key={id} testID={`approval-example-${id}`}>
            <PermissionCard taskId="sample" matterTitle={matterTitle} scroll={scroll} v={v} />
          </View> : null
        })}
        <View testID="approval-example-terminal-command">
          <TerminalPermission pending={{ tool: 'Bash', summary: 'npm test\nnpm run preview' }} source={demoName('claude')} projectPath={projectPath} scroll={scroll} />
        </View>
        <View testID="approval-example-terminal-edit">
          <TerminalPermission pending={CliSessionRow.shape.pending.unwrap().parse({
            tool: 'Edit', summary: JSON.stringify(terminalEdit), display: toolPermissionDisplay('Edit', terminalEdit), cwd: projectPath, truncated: false, since: 1,
          })} source={demoName('claude')} projectPath={projectPath} scroll={scroll} />
        </View>
        <View testID="approval-example-terminal-command-at-limit">
          <TerminalPermission pending={{ tool: 'Bash', summary: commandAtLimit }} source={demoName('claude')} projectPath={projectPath} scroll={scroll} />
        </View>
      </ScrollView>
    </SafeAreaView>
  </OfflineReviewProvider>
}
